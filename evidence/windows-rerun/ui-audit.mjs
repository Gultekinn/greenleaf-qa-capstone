import { chromium } from '@playwright/test';
import fs from 'node:fs';
const browser = await chromium.launch({channel:'chrome',headless:true});
const page = await browser.newPage({viewport:{width:390,height:844}});
await page.goto('http://localhost:3000');
await page.getByTestId('add-to-cart-btn-p-apples').click();
await page.getByTestId('nav-cart').click();
await page.getByTestId('proceed-to-checkout-btn').click();
await page.getByTestId('checkout-submit-btn').scrollIntoViewIfNeeded();
const submit=await page.getByTestId('checkout-submit-btn').boundingBox();
const promo=await page.getByTestId('promo-apply-btn').boundingBox();
const hit=await page.getByTestId('checkout-submit-btn').evaluate(el=>{const r=el.getBoundingClientRect();const top=document.elementFromPoint(r.x+r.width/2,r.y+r.height/2);return {submitIsTopElement:top===el||el.contains(top),topTestId:top?.getAttribute('data-testid'),topText:top?.textContent};});
const overlap=Math.max(0,Math.min(submit.x+submit.width,promo.x+promo.width)-Math.max(submit.x,promo.x))*Math.max(0,Math.min(submit.y+submit.height,promo.y+promo.height)-Math.max(submit.y,promo.y));
await page.screenshot({path:'evidence/mobile-overlap.png',fullPage:true});
await page.setViewportSize({width:1280,height:900});
await page.getByTestId('checkout-submit-btn').click();
const validation=await page.getByTestId('checkout-form').evaluate(form=>({valid:form.checkValidity(),invalidFields:[...form.querySelectorAll(':invalid')].map(el=>el.getAttribute('data-testid'))}));
const results={viewport:{width:390,height:844},submitBox:submit,promoBox:promo,overlapArea:overlap,hitTest:hit,requiredFieldsCheck:validation,urlAfterEmptySubmit:page.url()};
fs.writeFileSync('evidence/ui-audit.json',JSON.stringify(results,null,2));
console.log(JSON.stringify(results,null,2));
await browser.close();
if(overlap<=0||hit.submitIsTopElement||validation.valid)process.exitCode=1;
